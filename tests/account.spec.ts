import { expect, test, type Page } from '@playwright/test'

test('opens login and registration over the current page and restores focus on close', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'O mobile usa telas inteiras de autenticação.')
  await page.goto('/?tab=new')
  const enter = page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('button', { name: 'Entrar', exact: true })
  const originalUrl = page.url()
  await enter.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveAccessibleName('Entrar na conta')
  await expect(page).toHaveURL(originalUrl)
  await testInfo.attach('modal-entrar', { body: await dialog.screenshot({ scale: 'css' }), contentType: 'image/png' })
  await dialog.getByRole('button', { name: 'Modo Criar conta' }).click()
  await expect(dialog).toHaveAccessibleName('Criar conta')
  await expect(dialog.getByLabel('Nome de usuário')).toBeVisible()
  await expect(dialog.getByLabel('Confirmar senha')).toBeVisible()
  await testInfo.attach('modal-criar-conta', { body: await dialog.screenshot({ scale: 'css' }), contentType: 'image/png' })
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(enter).toBeFocused()
  await expect(page).toHaveURL(originalUrl)
  await enter.click()
  await expect(dialog).toHaveAccessibleName('Entrar na conta')
  await dialog.getByRole('button', { name: 'Fechar formulário' }).click()
  await expect(dialog).not.toBeVisible()
})

async function login(page: Page, user = 'ana', password = 'KurioDemo123!') {
  await page.getByLabel('E-mail', { exact: true }).fill(user + '@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).not.toHaveURL(/\/(login|register)(\?|$)/)
}

