test('rolls back a failed favorite change and isolates saved favorites by account', async ({ page }) => {
  await page.goto('/nfts/emerald-ape-042')
  await page.getByRole('link', { name: 'Entre para favoritar' }).click()
  await login(page)
  const add = page.getByRole('button', { name: 'Favoritar NFT' })
  const remove = page.getByRole('button', { name: 'Remover dos favoritos' })
  await add.click()
  await expect(remove).toBeEnabled()
  await page.reload()
  await expect(remove).toBeEnabled()
  await page.evaluate(() => fetch('/__demo/favorites/fail-next', { method: 'POST' }).then((response) => response.status))
  await remove.click()
  await expect(page.getByRole('alert')).toContainText('Não foi possível atualizar os favoritos')
  await expect(remove).toHaveAttribute('aria-pressed', 'true')

  if (page.viewportSize()!.width < 768) await page.getByRole('link', { name: 'Voltar ao mercado' }).click()
  await page.getByRole('link', { name: 'Favoritos', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Emerald Ape #042' })).toBeVisible()
  await page.getByRole('button', { name: 'Sair' }).click()
  await page.getByRole('link', { name: 'Entrar e continuar' }).click()
  await login(page, 'bia', 'KurioDemo456!')
  await expect(page.getByText('Você ainda não tem favoritos.')).toBeVisible()
  await page.getByRole('button', { name: 'Sair' }).click()
  await page.getByRole('link', { name: 'Entrar e continuar' }).click()
  await login(page)
  await page.getByRole('link', { name: 'Emerald Ape #042' }).click()
  await remove.click()
  await expect(add).toBeEnabled()
  await page.reload()
  await expect(add).toBeEnabled()
})

test('expires checkout, protects the draft across account switches and resumes for its owner', async ({ page }) => {
  await page.goto('/nfts/emerald-ape-042')
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await expect(page.getByText('NFT adicionado ao carrinho.')).toBeVisible()
  await page.goto('/checkout')
  await page.getByRole('link', { name: 'Entrar e continuar' }).click()
  await login(page)
  await page.getByLabel('Nome de exibição').fill('Rascunho de Ana')
  const response = await page.evaluate(() => fetch('/__demo/session/expire', {
    method: 'POST', headers: { Authorization: 'Bearer ' + localStorage.getItem('kurio.session') },
  }).then((response) => response.status))
  expect(response).toBe(204)
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await expect(page.getByText(/Sua sessão expirou/)).toBeVisible()
  await page.getByRole('link', { name: 'Entrar e continuar' }).click()
  await login(page, 'bia', 'KurioDemo456!')
  await expect(page.getByText('Seu carrinho está vazio.')).toBeVisible()
  await expect(page.getByLabel('Nome de exibição')).toHaveCount(0)
  await page.getByRole('button', { name: 'Sair' }).click()
  await page.getByRole('link', { name: 'Entrar e continuar' }).click()
  await login(page)
  await expect(page.getByLabel('Nome de exibição')).toHaveValue('Rascunho de Ana')
})
